/** A slot the plan says should exist on a given day. */
export interface ExpectedShift {
  date: string;
  code: string;
  dTag: string;
  definition: ShiftDefinition;
  title: string;
  /** Unix seconds. */
  start: number;
  end: number;
  tzid: string;
  location?: string;
  capacity: number;
  description?: string;
  /** Wall-clock `HH:MM–HH:MM`, for the derived content. */
  timeRange: string;
}

/** Whether a definition runs on a date. */
export function runsOn(def: Pick<ShiftDefinition, 'enabled' | 'days'>, date: string): boolean {
  if (!def.enabled) return false;
  if (!def.days?.length) return true;
  return def.days.includes(isoWeekday(date));
}

/** One expected slot, or null when the definition does not run that day. */
export function expectedShift(plan: ShiftPlan, def: ShiftDefinition, groupId: string, date: string): ExpectedShift | null {
  if (!runsOn(def, date)) return null;
  const location = def.location ?? plan.location;
  return {
    date,
    code: def.code,
    dTag: shiftDTag({ groupId, date, code: def.code }),
    definition: def,
    title: def.title,
    start: localToUnix(date, def.start, plan.tzid),
    end: localToUnix(date, def.end, plan.tzid),
    tzid: plan.tzid,
    ...(location ? { location } : {}),
    capacity: def.capacity,
    ...(def.description ? { description: def.description } : {}),
    timeRange: `${def.start}–${def.end}`,
  };
}

/**
 * Every slot the plan expects from `fromDate` for `days` days — the set the
 * coordinator materialises, in date then start order.
 */
export function expectedShifts(plan: ShiftPlan, groupId: string, fromDate: string, days = plan.horizonDays): ExpectedShift[] {
  const out: ExpectedShift[] = [];
  for (let i = 0; i < days; i++) {
    const date = addDays(fromDate, i);
    for (const def of sortDefinitions(plan.shifts)) {
      const e = expectedShift(plan, def, groupId, date);
      if (e) out.push(e);
    }
  }
  return out;
}

/** `HH:MM` wall-clock of a unix instant in `tzid`. */
export function wallClock(unixSeconds: number, tzid: string): string {
  try {
    return new Intl.DateTimeFormat('en-GB', { hour: '2-digit', minute: '2-digit', hour12: false, timeZone: tzid }).format(
      new Date(unixSeconds * 1000),
    );
  } catch {
    return new Date(unixSeconds * 1000).toISOString().slice(11, 16);
  }
}

/**
 * Adopt a plan from what is already on the wall: one definition per code,
 * taken from the newest occurrence carrying it (its title, wall-clock
 * times in the zone it was published in, capacity, location). This is how
 * a holon whose shifts Elinor has been publishing gets a plan that matches
 * them, instead of a seed catalog that marks every one of them stale.
 * Returns null when there is nothing to adopt.
 */
export function planFromOccurrences(occurrences: ShiftOccurrence[], fallbackTzid = 'UTC'): ShiftPlan | null {
  if (!occurrences.length) return null;
  const newest = new Map<string, ShiftOccurrence>();
  for (const o of occurrences) {
    const prev = newest.get(o.code);
    if (!prev || o.createdAt > prev.createdAt || (o.createdAt === prev.createdAt && o.start > prev.start)) {
      newest.set(o.code, o);
    }
  }
  // The zone: whatever most occurrences were published in.
  const zones = new Map<string, number>();
  for (const o of occurrences) if (o.startTzid && isValidTimeZone(o.startTzid)) zones.set(o.startTzid, (zones.get(o.startTzid) ?? 0) + 1);
  const tzid = [...zones.entries()].sort((a, b) => b[1] - a[1])[0]?.[0] ?? fallbackTzid;
  // The location: the one most occurrences carry; a definition only keeps
  // its own when it differs.
  const places = new Map<string, number>();
  for (const o of occurrences) if (o.location) places.set(o.location, (places.get(o.location) ?? 0) + 1);
  const location = [...places.entries()].sort((a, b) => b[1] - a[1])[0]?.[0];
  const shifts: ShiftDefinition[] = [];
  for (const o of newest.values()) {
    const v = validateShiftDefinition({
      code: o.code,
      title: o.title,
      start: wallClock(o.start, tzid),
      end: wallClock(o.end, tzid),
      capacity: o.capacity ?? DEFAULT_SHIFT_CAPACITY,
      enabled: true,
      ...(o.location && o.location !== location ? { location: o.location } : {}),
    });
    if (v.ok) shifts.push({ ...v.value, code: o.code });
  }
  if (!shifts.length) return null;
  return { tzid, ...(location ? { location } : {}), horizonDays: DEFAULT_HORIZON_DAYS, shifts: sortDefinitions(shifts) };
}

