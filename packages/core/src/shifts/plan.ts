// Reconciliation — the plan against the live schedule
// ---------------------------------------------------------------------------

/**
 *  - `unpublished`: the plan expects it, no occurrence is on the relay yet.
 *  - `unstaffed`:   published, nobody on it.
 *  - `short`:       published, some people, still below capacity.
 *  - `covered`:     published and at (or over) capacity.
 *  - `open`:        published with no capacity — never "missing".
 *  - `stale`:       published, but the plan no longer expects it.
 */
export type ShiftCoverageState = 'unpublished' | 'unstaffed' | 'short' | 'covered' | 'open' | 'stale';

export interface ShiftCoverage {
  key: string;
  date: string;
  code: string;
  state: ShiftCoverageState;
  expected?: ExpectedShift;
  occurrence?: ShiftOccurrence;
  /** People enrolled (persons, with an identity map). */
  enrolled: string[];
  /** Spots still open, 0 when full or when the shift has no capacity. */
  missing: number;
  /**
   * The published occurrence disagrees with the plan (time, title, place or
   * capacity) — a republish would bring it in line.
   */
  drifted: boolean;
}

export interface ShiftCoverageSummary {
  /** Slots the plan expects in the window. */
  expected: number;
  unpublished: number;
  unstaffed: number;
  short: number;
  covered: number;
  stale: number;
  /** Spots still open across every published shift in the window. */
  spotsOpen: number;
  /** Spots filled across every published shift with a capacity. */
  spotsFilled: number;
  spotsTotal: number;
}

/** Coverage state of one published occurrence on its own (no plan). */
export function coverageOf(
  occurrence: ShiftOccurrence,
  rsvps: Iterable<ShiftRsvp>,
  identity?: ShiftIdentityMap,
): Pick<ShiftCoverage, 'state' | 'enrolled' | 'missing'> {
  const enrolled = enrolledPubkeys(occurrence, rsvps, identity);
  if (occurrence.capacity === undefined) return { state: 'open', enrolled, missing: 0 };
  const missing = Math.max(0, occurrence.capacity - enrolled.length);
  const state: ShiftCoverageState = enrolled.length === 0 && missing > 0 ? 'unstaffed' : missing > 0 ? 'short' : 'covered';
  return { state, enrolled, missing };
}

function drifts(e: ExpectedShift, o: ShiftOccurrence): boolean {
  return (
    e.start !== o.start ||
    e.end !== o.end ||
    e.title !== o.title ||
    e.capacity !== o.capacity ||
    (e.location ?? '') !== (o.location ?? '')
  );
}

/**
 * Line the plan's expected slots up against what is published and who is
 * on it. Occurrences from a coordinator other than `coordinatorPubkey`
 * (when given) are ignored, so a foreign 31923 never counts as ours.
 */
export function reconcileSchedule(
  expected: ExpectedShift[],
  occurrences: ShiftOccurrence[],
  rsvps: Iterable<ShiftRsvp>,
  opts: { identity?: ShiftIdentityMap; coordinatorPubkey?: string; window?: { since?: number; until?: number } } = {},
): { items: ShiftCoverage[]; summary: ShiftCoverageSummary } {
  const rsvpList = [...rsvps];
  const coord = opts.coordinatorPubkey?.toLowerCase();
  const inWindow = (start: number, end: number) =>
    (opts.window?.since === undefined || end >= opts.window.since) &&
    (opts.window?.until === undefined || start <= opts.window.until);
  const byKey = new Map<string, ShiftOccurrence>();
  for (const o of occurrences) {
    if (coord && o.pubkey.toLowerCase() !== coord) continue;
    if (!inWindow(o.start, o.end)) continue;
    byKey.set(`${o.date}-${o.code}`, o);
  }
  const items: ShiftCoverage[] = [];
  const seen = new Set<string>();
  for (const e of expected) {
    if (!inWindow(e.start, e.end)) continue;
    const key = `${e.date}-${e.code}`;
    seen.add(key);
    const occ = byKey.get(key);
    if (!occ) {
      items.push({ key, date: e.date, code: e.code, state: 'unpublished', expected: e, enrolled: [], missing: e.capacity, drifted: false });
      continue;
    }
    const c = coverageOf(occ, rsvpList, opts.identity);
    items.push({ key, date: e.date, code: e.code, ...c, expected: e, occurrence: occ, drifted: drifts(e, occ) });
  }
  for (const [key, occ] of byKey) {
    if (seen.has(key)) continue;
    const c = coverageOf(occ, rsvpList, opts.identity);
    items.push({ key, date: occ.date, code: occ.code, ...c, state: 'stale', occurrence: occ, drifted: false });
  }
  items.sort((a, b) => {
    const sa = a.expected?.start ?? a.occurrence?.start ?? 0;
    const sb = b.expected?.start ?? b.occurrence?.start ?? 0;
    return sa - sb || a.code.localeCompare(b.code);
  });
  const summary: ShiftCoverageSummary = {
    expected: items.filter((i) => i.expected).length,
    unpublished: 0,
    unstaffed: 0,
    short: 0,
    covered: 0,
    stale: 0,
    spotsOpen: 0,
    spotsFilled: 0,
    spotsTotal: 0,
  };
  for (const i of items) {
    if (i.state === 'unpublished') summary.unpublished++;
    else if (i.state === 'stale') summary.stale++;
    else if (i.state === 'unstaffed') summary.unstaffed++;
    else if (i.state === 'short') summary.short++;
    else if (i.state === 'covered') summary.covered++;
    if (i.occurrence?.capacity !== undefined) {
      summary.spotsOpen += i.missing;
      summary.spotsFilled += Math.min(i.enrolled.length, i.occurrence.capacity);
      summary.spotsTotal += i.occurrence.capacity;
    }
  }
  return { items, summary };
}

/** The address a coordinator's occurrence for an expected slot would have. */
export function expectedAddress(coordinatorPubkey: string, e: Pick<ExpectedShift, 'dTag'>): string {
  return shiftAddress(coordinatorPubkey, e.dTag);
}

