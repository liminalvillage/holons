/** Store shape the plan I/O needs (the kiosk's ReaStore, a HoloSphere, …). */
export interface ShiftPlanStore {
  get(holon: string, lens: string, key?: string): Promise<unknown>;
  put(holon: string, lens: string, value: unknown): Promise<unknown>;
}

function cleanDefinition(raw: unknown): ShiftDefinition | null {
  if (!raw || typeof raw !== 'object') return null;
  const r = raw as Record<string, unknown>;
  const code = String(r.code ?? '');
  if (!isValidShiftCode(code)) return null;
  const v = validateShiftDefinition({ ...(r as ShiftDefinitionInput), code });
  return v.ok ? { ...v.value, code } : null;
}

/**
 * The plan on a settings record, or null when none is stored. Malformed
 * definitions are dropped rather than failing the whole plan, so one bad
 * hand edit cannot blank a board.
 */
export function readShiftPlan(settings: unknown): ShiftPlan | null {
  const doc = Array.isArray(settings) ? settings.find((e) => e && typeof e === 'object' && SHIFT_PLAN_KEY in e) : settings;
  const raw = doc && typeof doc === 'object' ? (doc as Record<string, unknown>)[SHIFT_PLAN_KEY] : undefined;
  if (!raw || typeof raw !== 'object') return null;
  const p = raw as Record<string, unknown>;
  const tzid = typeof p.tzid === 'string' && isValidTimeZone(p.tzid) ? p.tzid : 'UTC';
  const horizon = Number(p.horizonDays);
  const shifts = Array.isArray(p.shifts)
    ? p.shifts.map(cleanDefinition).filter((d): d is ShiftDefinition => d !== null)
    : [];
  const location = typeof p.location === 'string' && p.location.trim() ? p.location.trim() : undefined;
  return {
    tzid,
    ...(location ? { location } : {}),
    horizonDays: Number.isInteger(horizon) && horizon >= 1 && horizon <= 60 ? horizon : DEFAULT_HORIZON_DAYS,
    shifts: sortDefinitions(shifts),
  };
}

/** Strip a plan to what is stored (no undefined fields — Holosphere warns on those). */
export function normalizeShiftPlan(plan: ShiftPlan): ShiftPlan {
  const tzid = isValidTimeZone(plan.tzid) ? plan.tzid : 'UTC';
  const horizon = Number(plan.horizonDays);
  const shifts = sortDefinitions(
    plan.shifts.map(cleanDefinition).filter((d): d is ShiftDefinition => d !== null),
  );
  const location = plan.location?.trim();
  return {
    tzid,
    ...(location ? { location } : {}),
    horizonDays: Number.isInteger(horizon) && horizon >= 1 && horizon <= 60 ? horizon : DEFAULT_HORIZON_DAYS,
    shifts,
  };
}

/** Load the holon's plan from its settings record. */
export async function loadShiftPlan(store: Pick<ShiftPlanStore, 'get'>, holonId: string): Promise<ShiftPlan | null> {
  let existing: unknown = null;
  try {
    existing = await store.get(String(holonId), 'settings', String(holonId));
  } catch {
    // Unreadable settings read as "no plan".
  }
  return readShiftPlan(existing);
}

/**
 * Write the plan onto the settings record, preserving every other field
 * (allocation, name, …) the way the flows settings writer does.
 */
export async function saveShiftPlan(store: ShiftPlanStore, holonId: string, plan: ShiftPlan): Promise<ShiftPlan> {
  let existing: unknown = null;
  try {
    existing = await store.get(String(holonId), 'settings', String(holonId));
  } catch {
    // A missing record is created below.
  }
  const doc = Array.isArray(existing)
    ? (existing.find((e) => e && typeof e === 'object' && (e as { id?: unknown }).id === String(holonId)) ?? {})
    : existing && typeof existing === 'object'
      ? existing
      : {};
  const clean = normalizeShiftPlan(plan);
  await store.put(String(holonId), 'settings', {
    ...(doc as object),
    id: String(holonId),
    [SHIFT_PLAN_KEY]: clean,
  });
  return clean;
}
