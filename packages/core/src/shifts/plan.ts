// The shift PLAN: a holon's catalog of recurring shifts and the rules that
// turn it into concrete occurrences and, against the live schedule, into
// "what is missing". Pure — no network, no signing, no store; the store I/O
// for the plan itself is the two small functions at the bottom.
//
// The catalog mirrors Elinor's (src/shifts.js there): the same seeds, the
// same validation, the same code generator, so a plan edited on a kiosk and
// one edited in Elinor's Mini App describe the same schedule. Elinor runs
// every enabled shift every day; `days` is the one extension.

import type { ShiftDefinition, ShiftOccurrence, ShiftPlan, ShiftRsvp } from './types.js';
import { enrolledPubkeys, isValidShiftCode, shiftAddress, shiftDTag, type ShiftIdentityMap } from './protocol.js';

/** Elinor's default capacity per shift. */
export const DEFAULT_SHIFT_CAPACITY = 2;
/** Elinor materialises two weeks ahead. */
export const DEFAULT_HORIZON_DAYS = 14;
/** Key of the plan on the holon's `settings` record. */
export const SHIFT_PLAN_KEY = 'shifts';

/** Elinor's seed catalog — what a fresh plan starts from. */
export const DEFAULT_SHIFT_DEFINITIONS: readonly ShiftDefinition[] = Object.freeze([
  { code: 'mc', title: 'Morning Cleaning', start: '08:30', end: '10:30', capacity: DEFAULT_SHIFT_CAPACITY, enabled: true },
  { code: 'lp', title: 'Lunch Preparation', start: '10:30', end: '12:30', capacity: DEFAULT_SHIFT_CAPACITY, enabled: true },
  { code: 'lc', title: 'Lunch Cleaning', start: '14:00', end: '16:00', capacity: DEFAULT_SHIFT_CAPACITY, enabled: true },
  { code: 'dp', title: 'Dinner Preparation', start: '16:30', end: '18:30', capacity: DEFAULT_SHIFT_CAPACITY, enabled: true },
  { code: 'dc', title: 'Dinner Cleaning', start: '20:30', end: '22:30', capacity: DEFAULT_SHIFT_CAPACITY, enabled: true },
].map((d) => Object.freeze({ ...d })));

const TIME_RE = /^([01]\d|2[0-3]):[0-5]\d$/;
const DATE_RE = /^\d{4}-\d{2}-\d{2}$/;

/** A fresh plan: Elinor's seeds in the given zone. */
export function defaultShiftPlan(tzid = 'UTC', location?: string): ShiftPlan {
  return {
    tzid,
    ...(location ? { location } : {}),
    horizonDays: DEFAULT_HORIZON_DAYS,
    shifts: DEFAULT_SHIFT_DEFINITIONS.map((d) => ({ ...d })),
  };
}

/** True when `tzid` is a zone this runtime can format in. */
export function isValidTimeZone(tzid: string): boolean {
  try {
    new Intl.DateTimeFormat('en-US', { timeZone: tzid });
    return true;
  } catch {
    return false;
  }
}

export type ShiftDefinitionInput = Partial<ShiftDefinition> & { title?: unknown };

/**
 * Elinor's `validateDef`, field for field, plus `days`/`location`. Returns
 * the clean definition or a human-readable error. The code is validated when
 * given and generated by `upsertShiftDefinition` when not.
 */
export function validateShiftDefinition(
  input: ShiftDefinitionInput,
): { ok: true; value: Omit<ShiftDefinition, 'code'> & { code?: string } } | { ok: false; error: string } {
  const title = String(input.title ?? '').trim();
  if (!title || title.length > 40) return { ok: false, error: 'Title must be 1–40 characters.' };
  const start = String(input.start ?? '');
  const end = String(input.end ?? '');
  if (!TIME_RE.test(start) || !TIME_RE.test(end)) return { ok: false, error: 'Times must be HH:MM (24h).' };
  if (start >= end) return { ok: false, error: 'End time must be after start time.' };
  const capacity = Number(input.capacity ?? DEFAULT_SHIFT_CAPACITY);
  if (!Number.isInteger(capacity) || capacity < 1 || capacity > 20) {
    return { ok: false, error: 'People needed must be 1–20.' };
  }
  const description = String(input.description ?? '').trim().slice(0, 300);
  const code = input.code === undefined || input.code === '' ? undefined : String(input.code);
  if (code !== undefined && !isValidShiftCode(code)) return { ok: false, error: 'Invalid shift code.' };
  let days: number[] | undefined;
  if (Array.isArray(input.days) && input.days.length) {
    days = [...new Set(input.days.map(Number))].filter((d) => Number.isInteger(d) && d >= 1 && d <= 7).sort();
    if (!days.length) return { ok: false, error: 'Days must be ISO weekdays 1–7.' };
    if (days.length === 7) days = undefined; // every day is the default
  }
  const location = String(input.location ?? '').trim().slice(0, 80);
  return {
    ok: true,
    value: {
      ...(code !== undefined ? { code } : {}),
      title,
      start,
      end,
      capacity,
      enabled: input.enabled === undefined ? true : Boolean(input.enabled),
      ...(description ? { description } : {}),
      ...(days ? { days } : {}),
      ...(location ? { location } : {}),
    },
  };
}

/** Elinor's `genCode`: initials of the title, disambiguated against the catalog. */
export function generateShiftCode(title: string, taken: Iterable<string>): string {
  const used = new Set(taken);
  let base = title
    .toLowerCase()
    .replace(/[^a-z0-9\s]/g, ' ')
    .trim()
    .split(/\s+/)
    .map((w) => w[0])
    .join('')
    .slice(0, 8);
  if (base.length < 2) base = title.toLowerCase().replace(/[^a-z0-9]/g, '').slice(0, 4) || 'shift';
  let code = base;
  let i = 2;
  while (used.has(code)) code = `${base}${i++}`;
  return code;
}

/**
 * Add or replace one definition, returning the new plan and the code it
 * landed on. Unknown codes on an edit are an error, so a stale form cannot
 * resurrect a removed shift under its old code by accident.
 */
export function upsertShiftDefinition(
  plan: ShiftPlan,
  input: ShiftDefinitionInput,
): { ok: true; plan: ShiftPlan; code: string; created: boolean } | { ok: false; error: string } {
  const v = validateShiftDefinition(input);
  if (!v.ok) return v;
  const codes = plan.shifts.map((s) => s.code);
  const created = v.value.code === undefined;
  const code = v.value.code ?? generateShiftCode(v.value.title, codes);
  const idx = codes.indexOf(code);
  if (!created && idx < 0) return { ok: false, error: 'Unknown shift.' };
  const def: ShiftDefinition = { ...v.value, code };
  const shifts = idx < 0 ? [...plan.shifts, def] : plan.shifts.map((s, i) => (i === idx ? def : s));
  return { ok: true, plan: { ...plan, shifts: sortDefinitions(shifts) }, code, created: idx < 0 };
}

/** Drop a definition from the catalog. Removing an unknown code is a no-op. */
export function removeShiftDefinition(plan: ShiftPlan, code: string): ShiftPlan {
  return { ...plan, shifts: plan.shifts.filter((s) => s.code !== code) };
}

/** Elinor's ordering: by start time, then code. */
export function sortDefinitions(shifts: ShiftDefinition[]): ShiftDefinition[] {
  return [...shifts].sort((a, b) => a.start.localeCompare(b.start) || a.code.localeCompare(b.code));
}

// ---------------------------------------------------------------------------
// Time — DST-safe wall-clock → unix, the way Elinor's time.js does it
// ---------------------------------------------------------------------------

function tzOffsetMs(tzid: string, at: Date): number {
  const dtf = new Intl.DateTimeFormat('en-US', {
    timeZone: tzid,
    hour12: false,
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
    hour: '2-digit',
    minute: '2-digit',
    second: '2-digit',
  });
  const p: Record<string, string> = {};
  for (const part of dtf.formatToParts(at)) p[part.type] = part.value;
  const asUtc = Date.UTC(+p.year, +p.month - 1, +p.day, +p.hour % 24, +p.minute, +p.second);
  return asUtc - at.getTime();
}

/** `YYYY-MM-DD` + `HH:MM` in `tzid` → unix seconds. */
export function localToUnix(date: string, time: string, tzid: string): number {
  const [y, m, d] = date.split('-').map(Number);
  const [hh, mm] = time.split(':').map(Number);
  let guess = Date.UTC(y, m - 1, d, hh, mm);
  for (let i = 0; i < 2; i++) guess = Date.UTC(y, m - 1, d, hh, mm) - tzOffsetMs(tzid, new Date(guess));
  return Math.floor(guess / 1000);
}

/** Today's `YYYY-MM-DD` in `tzid`. */
export function todayIn(tzid: string, now: Date = new Date()): string {
  return new Intl.DateTimeFormat('en-CA', { timeZone: tzid, year: 'numeric', month: '2-digit', day: '2-digit' }).format(now);
}

export function addDays(date: string, n: number): string {
  const [y, m, d] = date.split('-').map(Number);
  return new Date(Date.UTC(y, m - 1, d + n, 12)).toISOString().slice(0, 10);
}

/** ISO weekday (1 = Monday … 7 = Sunday) of a `YYYY-MM-DD`. */
export function isoWeekday(date: string): number {
  const [y, m, d] = date.split('-').map(Number);
  const dow = new Date(Date.UTC(y, m - 1, d, 12)).getUTCDay();
  return dow === 0 ? 7 : dow;
}

export function isValidDate(date: string): boolean {
  return DATE_RE.test(date) && !Number.isNaN(Date.parse(`${date}T12:00:00Z`));
}

